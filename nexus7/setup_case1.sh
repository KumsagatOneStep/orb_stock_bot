#!/usr/bin/env bash
set -e
# NEXUS-7 :: ДЕЛО #001 — ПРИЗРАЧНЫЕ ФАЙЛЫ
# Setup script — creates broken environment for the player to fix

CASE_DIR="$HOME/nexus7/case1"

# ── Пересоздать рабочую директорию ───────────────────────────────────────────
rm -rf "$CASE_DIR"
mkdir -p "$CASE_DIR/system"
mkdir -p "$CASE_DIR/backup"
mkdir -p "$CASE_DIR/trash"

# ── Создать конфиг (намеренно скрытый: права 000) ────────────────────────────
cat > "$CASE_DIR/backup/nexus.conf.bak" <<'CONF'
NEXUS-7 CONFIG v2.089
CORE_FREQ=4.2GHz
MEMORY=128TB
STATUS=OPERATIONAL
CONF

chmod 000 "$CASE_DIR/backup/nexus.conf.bak"

# ── Создать файлы-приманки в trash/ ──────────────────────────────────────────
echo "# OLD CONFIG — DEPRECATED" > "$CASE_DIR/trash/old_config.txt"
echo "TEMP=0x7F3A"               > "$CASE_DIR/trash/.nexus_temp"
echo "NEXUS-7 CONFIG v0.001"     > "$CASE_DIR/trash/nexus_v1.conf"

# ── Создать брифинг ───────────────────────────────────────────────────────────
cat > "$CASE_DIR/briefing.txt" <<'BRIEFING'
╔══════════════════════════════════════════════════════════════╗
║          N E X U S - 7   //   С Е К Т О Р   А Л Ь Ф А       ║
║                  ДЕЛО #001 — ПРИЗРАЧНЫЕ ФАЙЛЫ                ║
╚══════════════════════════════════════════════════════════════╝

ВХОДЯЩЕЕ СООБЩЕНИЕ :: ПРИОРИТЕТ КРИТИЧЕСКИЙ
ОТ   : Оракул-9, центральный ИИ системы
КОМУ : Агент [ТЫ]

──────────────────────────────────────────────────────────────
СИТУАЦИЯ:

  Корпоративный сервер NEXUS-7 потерял главный конфиг.
  Без него ядро системы работает вхолостую — 128 терабайт
  памяти простаивают, частота ядра не выставлена.

  Кто-то намеренно заблокировал файл и спрятал его в архивах.
  Система рушится. У тебя есть один шанс.

──────────────────────────────────────────────────────────────
ЗАДАНИЕ:

  1. Найди конфигурационный файл где-то внутри case1/
     ПОДСКАЗКА: find ~/nexus7/case1 -name "*.conf*"

  2. Восстанови права доступа к файлу
     ПОДСКАЗКА: chmod 644 <путь_к_файлу>

  3. Скопируй файл в боевую директорию:
     system/nexus.conf
     ПОДСКАЗКА: cp <источник> system/nexus.conf

  4. Проверь результат:
     bash ~/nexus7/check_case1.sh

──────────────────────────────────────────────────────────────
НАВЫКИ В ДЕЛЕ: find  |  chmod  |  cp  |  ls

  Удачи, агент. NEXUS-7 ждёт тебя.
╚══════════════════════════════════════════════════════════════╝
BRIEFING

# ── Показать брифинг игроку ───────────────────────────────────────────────────
echo ""
cat "$CASE_DIR/briefing.txt"
echo ""
echo "  Рабочая директория: $CASE_DIR"
echo "  Начни здесь:        cd ~/nexus7/case1"
echo ""
